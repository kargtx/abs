const dicts = { ru, en };

export function translate(lang: "ru" | "en", key: TKey, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? ru[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useStore((s) => s.settings.language);
  return (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function useLang() {
  return useStore((s) => s.settings.language);
}

