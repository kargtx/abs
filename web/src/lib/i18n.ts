/** Русская плюрализация: 1 неделя / 4 недели / 8 недель. */
export function plural(lang: "ru" | "en", n: number, forms: { ru: [string, string, string]; en: [string, string] }): string {
  if (lang === "en") return `${n} ${n === 1 ? forms.en[0] : forms.en[1]}`;
  const m10 = n % 10;
  const m100 = n % 100;
  const f = m10 === 1 && m100 !== 11 ? 0 : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 1 : 2;
  return `${n} ${forms.ru[f]}`;
}

